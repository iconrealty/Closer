// Helpers to generate dates relative to current day
const getRelativeDateString = (offsetDays: number): string => {
  const d = new Date();
  d.setDate(d.getDate() + offsetDays);
  return d.toISOString().split('T')[0];
};

const getRelativeIsoString = (offsetHours: number): string => {
  const d = new Date();
  d.setTime(d.getTime() + offsetHours * 3600 * 1000);
  return d.toISOString();
};

